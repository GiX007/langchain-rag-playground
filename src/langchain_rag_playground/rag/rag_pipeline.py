# Initialize the embeddings model and the llm
embeddings_model = OpenAIEmbeddings(model="text-embedding-3-small")
llm = init_chat_model(model="gpt-4o-mini", temperature=0.2)


def create_kb() -> Chroma:
    """Split the knowledge base into chunks and store them in a Chroma DB on disk."""

    # Split the knowledge base into chunks
    text_splitter = RecursiveCharacterTextSplitter(chunk_size=500, chunk_overlap=50)
    doc = Document(page_content=KNOWLEDGE_BASE, metadata={"source": "knowledge_base.md"})

    chunks = text_splitter.split_documents([doc])

    # One fixed id per chunk for demonstration
    for i, chunk in enumerate(chunks):
        chunk.metadata["id"] = f"chunk_{i+1}"

    # Create a Chroma vector store from the chunks
    vector_store = Chroma.from_documents(
        documents=chunks,
        embedding=embeddings_model,
        ids=[chunk.metadata["id"] for chunk in chunks],  # Same ids on every run -> Chroma overwrites instead of duplicating
        collection_name="knowledge_base",
        persist_directory=PERSIST_DIR,  # Directory to store the vector store
    )

    print(f"Split into {len(chunks)} chunks ({', '.join(str(len(c.page_content)) for c in chunks)} characters each).")
    print(f"Collections in '{PERSIST_DIR}' ({len(vector_store._client.list_collections())}): {vector_store._client.list_collections()}")

    return vector_store


def basic_rag() -> None:
    """Answer 3 test questions with a basic RAG chain."""

    # 1. Create the knowledge base vector store
    kb_vector_store = create_kb()

    # 2. Define a simple retriever that retrieves the top k most similar chunks from the knowledge base
    retriever = kb_vector_store.as_retriever(
        search_type="similarity",  # Use similarity search to find relevant chunks
        search_kwargs={"k": 2}  # Retrieve the top 2 most similar chunks
    )
    print(f"Retriever: {retriever}")

    # 3. Initialize the language model (LLM) for generating answers based on retrieved context
    llm = init_chat_model(model="gpt-4o-mini", temperature=0.2)

    # Define a simple prompt template for the RAG pipeline
    prompt = ChatPromptTemplate.from_template(
        """
You are a helpful assistant. Answer the question based only on the following context:

{context}

Question: {question}

Answer:


Make sure to answer in a concise and clear manner, and do not include any information that is not present in the context."""
    )

    # How to convert the retrieved documents into a single string for the context in the prompt
    def format_docs(docs: list[Document]) -> str:
        """Format retrieved documents into a single string for the prompt."""
        return "\n\n".join([f"Source: {doc.metadata['source']}\nContent: {doc.page_content}" for doc in docs])

    # 4. Create the RAG chain
    rag_chain = (
        # 1. Create context and question inputs for the prompt in a dictionary format. The context is generated by retrieving
        # relevant documents from the knowledge base and formatting them into a single string
        {"context": retriever | format_docs, "question": RunnablePassthrough()}  # RunnablePassthrough() passes the question directly to the prompt without any modification

        # 2. Pass the context and question to the prompt, which formats them into a single string that can be fed to the LLM,
        # and then pass the formatted prompt to the LLM for generating an answer. Finally, parse the output of the LLM into a
        # string format using StrOutputParser
        | prompt
        | llm
        | StrOutputParser()
    )

    # Test questions
    questions = [
        "What is LangChain?",
        "Who created LangChain?",
        "What is LangChain used for?",
    ]

    # Test the RAG chain with some questions
    print("\nBasic RAG:\n")
    for question in questions:
        answer = rag_chain.invoke(question)
        print(f"Q: {question}\nA: {answer}\n")


def demo_rag_with_sources() -> None:
    """Answer one question with a RAG chain that cites its sources."""

    vectorstore = create_kb()
    retriever = vectorstore.as_retriever(search_kwargs={"k": 3})

    prompt = ChatPromptTemplate.from_template(
        """
Answer the question based on the context below. Include which sources you used.

Context:
{context}

Question: {question}

Answer (include sources):"""
    )

    def format_docs_with_sources(docs: list[Document]) -> str:
        """Join the docs into one string, each with a number and its source."""
        formatted = []
        for i, doc in enumerate(docs):
            source = doc.metadata.get("source", "unknown")
            formatted.append(f"[{i+1}] {source}:\n{doc.page_content}")
        return "\n\n".join(formatted)

    rag_chain = (
        {
            "context": retriever | format_docs_with_sources,
            "question": RunnablePassthrough(),
        }
        | prompt
        | llm
        | StrOutputParser()
    )

    print("RAG with Sources:\n")
    answer = rag_chain.invoke("What are the core components of LangChain?")
    print("Q: What are the core components?\n")
    print(f"A: {answer}")


if __name__ == "__main__":
    # basic_rag()
    demo_rag_with_sources()